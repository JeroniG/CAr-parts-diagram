import { mkdir, readFile, writeFile } from 'node:fs/promises';
import {
  vehicle,
  systems,
  catalog,
  sources,
  oemParts,
  fitments,
  relationships,
  animations,
} from '../src/data/catalog.source';
import { rearHatch } from '../src/vehicles/rearHatch';
const manifest = JSON.parse(await readFile('public/models/smart-451/manifest.json', 'utf8'));
const assemblyAssets = await Promise.all(
  ['low', 'high'].map(async (lod) =>
    JSON.parse(await readFile(`public/models/smart-451/rear-hatch/${lod}.manifest.json`, 'utf8')),
  ),
);
const snapshot = {
  schemaVersion: 2,
  vehicle,
  systems,
  components: catalog,
  sources,
  oemParts,
  fitments,
  relationships,
  animations,
  modelAsset: manifest.asset,
  meshBindings: manifest.bindings,
  assemblies: [rearHatch],
  assemblyAssets,
};
await writeFile('src/data/catalog.snapshot.json', JSON.stringify(snapshot, null, 2) + '\n');
await mkdir('public/data', { recursive: true });
await writeFile('public/data/catalog.json', JSON.stringify(snapshot, null, 2) + '\n');
const snake = (s: string) => s.replace(/[A-Z]/g, (m) => '_' + m.toLowerCase());
const value = (v: unknown): string =>
  v == null
    ? 'null'
    : typeof v === 'boolean' || typeof v === 'number'
      ? String(v)
      : Array.isArray(v)
        ? 'array[' + v.map(value).join(',') + ']::text[]'
        : "'" + (typeof v === 'object' ? JSON.stringify(v) : String(v)).replaceAll("'", "''") + "'";
const sql: string[] = [
  '-- Generated by npm run export:catalog. Apply after migrations 001, 002 and 003.',
  'begin;',
];
function insert(table: string, record: Record<string, unknown>) {
  sql.push(
    `insert into ${table} (${Object.keys(record).map(snake).join(',')}) values (${Object.values(record).map(value).join(',')}) ${
      record.id
        ? `on conflict (id) do update set ${Object.keys(record)
            .filter((k) => k !== 'id')
            .map((k) => `${snake(k)}=excluded.${snake(k)}`)
            .join(',')}`
        : 'on conflict do nothing'
    };`,
  );
}
for (const s of sources) insert('source_record', s as unknown as Record<string, unknown>);
const { sourceIds, ...v } = vehicle;
insert('vehicle_configuration', v);
for (const sourceId of sourceIds) insert('vehicle_source', { vehicleConfigId: v.id, sourceId });
for (const s of systems) insert('vehicle_system', s as unknown as Record<string, unknown>);
for (const c of catalog) {
  const { sourceIds, ...record } = c;
  insert('component', record);
  for (const sourceId of sourceIds) insert('component_source', { componentId: c.id, sourceId });
}
for (const r of relationships)
  insert('component_relationship', {
    vehicleConfigId: vehicle.id,
    componentId: r.componentId,
    relatedComponentId: r.relatedComponentId,
    relationshipType: r.type,
    sourceId: r.evidence,
  });
insert('model_asset', manifest.asset);
for (const b of manifest.bindings) insert('mesh_binding', { ...b, vehicleConfigId: vehicle.id });
for (const m of assemblyAssets) {
  insert('model_asset', m.asset);
  insert('assembly_asset', {
    assemblyId: rearHatch.id,
    modelAssetId: m.asset.id,
    vehicleConfigId: vehicle.id,
    lod: m.lod,
    motionRig: m.motionRig,
  });
  for (const binding of m.bindings) {
    const b = { ...binding };
    delete b.explodedTransform;
    insert('mesh_binding', { ...b, vehicleConfigId: vehicle.id });
  }
}
for (const part of rearHatch.parts)
  insert('assembly_part_profile', {
    componentId: part.id,
    assemblyId: rearHatch.id,
    vehicleConfigId: vehicle.id,
    materialDescription: part.material,
    materialVerification: 'not-yet-verified',
    diagramCallout: part.callout,
    motionGroup: part.motion,
    explodedTransform: { translation: part.separation, rotation: [0, 0, 0] },
  });
for (const p of oemParts) insert('oem_part', p as unknown as Record<string, unknown>);
for (const f of fitments) insert('part_fitment', f as unknown as Record<string, unknown>);
for (const a of animations) insert('mechanism_animation', a as unknown as Record<string, unknown>);
for (const c of catalog.filter((c) => c.componentType === 'part')) {
  insert('part_definition', {
    id: `def-${c.id}`,
    name: c.name,
    description: c.description,
    sourceIds: c.sourceIds,
    identityStatus: c.sourceIds.some((id) => id.startsWith('owners-detail-'))
      ? 'source-backed'
      : 'unverified',
  });
  insert('part_instance', {
    id: c.id,
    definitionId: `def-${c.id}`,
    vehicleConfigId: c.vehicleConfigId,
    parentAssemblyId: c.parentComponentId,
    side: c.side,
  });
}
sql.push('commit;');
await writeFile('db/seed.sql', sql.join('\n') + '\n');
console.log(`Exported ${catalog.length} catalog records and normalized SQL seed.`);
